//! The third-party notices file: every registry component with the license
//! it declares, grouped by license.
//!
//! This is an attribution inventory built from declared metadata. oxAudit
//! does not read package contents during a dependency scan, so the file
//! carries no copyright lines and no license texts; the header says so.

use std::collections::BTreeMap;

use crate::report::{ScaComponent, ScaReport};

fn escape(text: &str) -> String {
    // Declared license text is registry-controlled; keep it from forming
    // markup or breaking out of a table cell.
    text.chars()
        .map(|character| match character {
            '|' | '<' | '>' | '`' | '[' | ']' | '*' | '_' | '\\' => {
                format!("\\{character}")
            }
            '\n' | '\r' => " ".into(),
            other => other.to_string(),
        })
        .collect()
}

fn heading(component: &ScaComponent) -> String {
    match (&component.license.expression, &component.license.declared) {
        (Some(expression), _) => expression.clone(),
        (None, Some(declared)) => declared.clone(),
        (None, None) => "No declared license".into(),
    }
}

/// Render the notices file as Markdown.
pub fn render(report: &ScaReport, project: &str) -> String {
    let mut groups: BTreeMap<String, Vec<&ScaComponent>> = BTreeMap::new();
    let mut local = 0usize;
    for component in &report.components {
        if !component.registry {
            // Git, path and workspace code is the project's own concern;
            // it is counted, not attributed.
            local += 1;
            continue;
        }
        groups
            .entry(heading(component))
            .or_default()
            .push(component);
    }
    let listed: usize = groups.values().map(Vec::len).sum();
    let mut out = format!(
        "# Third-party notices\n\nProject: {}\n\nGenerated by oxAudit at {} from declared package \
         metadata. This file lists {listed} third-party component(s) and the license each one \
         declares. It does not reproduce license texts or copyright notices: obtain those from \
         each package before distribution.\n",
        escape(project),
        escape(&report.summary.generated_at),
    );
    if local > 0 {
        out.push_str(&format!(
            "\n{local} component(s) from git, path or workspace sources are not listed.\n"
        ));
    }
    if let Some(undeclared) = groups.get("No declared license") {
        out.push_str(&format!(
            "\n{} component(s) declare no license. No license is not permission to use.\n",
            undeclared.len()
        ));
    }
    for (license, components) in &groups {
        out.push_str(&format!("\n## {}\n\n", escape(license)));
        out.push_str("| Component | Version | Ecosystem |\n| --- | --- | --- |\n");
        for component in components {
            out.push_str(&format!(
                "| {} | {} | {} |\n",
                escape(&component.name),
                escape(&component.version),
                escape(&component.ecosystem)
            ));
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::policy::ComponentPolicy;
    use crate::report::{assess, ComponentInput};

    #[test]
    fn components_are_grouped_by_license_and_local_code_is_counted_not_listed() {
        let input = |name: &str, license: Option<&str>, registry| ComponentInput {
            ecosystem: "npm".into(),
            name: name.into(),
            version: "1.0.0".into(),
            lockfile: "package-lock.json".into(),
            license: license.map(String::from),
            direct: None,
            registry,
            advisories: Vec::new(),
        };
        let report = assess(
            vec![
                input("b", Some("MIT"), true),
                input("a", Some("mit"), true),
                input("c", None, true),
                input("evil|<script>", Some("Custom *License*"), true),
                input("workspace-app", None, false),
            ],
            &[],
            &ComponentPolicy::default(),
            "2026-11-16T00:00:00Z".parse().unwrap(),
        );
        let text = render(&report, "/srv/api");
        assert!(text.contains("lists 4 third-party component(s)"), "{text}");
        assert!(text.contains("1 component(s) from git, path or workspace"));
        assert!(text.contains("1 component(s) declare no license"));
        let mit = text.find("## MIT").unwrap();
        assert!(text[mit..].find("| a |").unwrap() < text[mit..].find("| b |").unwrap());
        assert!(text.contains("## No declared license"));
        assert!(text.contains("## Custom \\*License\\*"));
        assert!(text.contains("evil\\|\\<script\\>"));
        assert!(!text.contains("workspace-app"));
        assert!(text.contains("does not reproduce license texts"));
    }
}
